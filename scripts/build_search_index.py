#!/usr/bin/env python3
"""B&S: builds bookstore-search-index.js (our own picks) for the bookstore search bar.
Reads the bookstore cards plus the JSON-LD on our book pages, Author of the Month and
Booker shortlist. Run from the repo root:  python3 scripts/build_search_index.py
"""
import glob, html, json, re

AFF = "https://bookshop.org/a/125864/"
SUBTITLES = {"California Dreams", "Milestones"}
books = {}   # key -> entry (key = ISBN13, or title for non-Bookshop titles)

def clean(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", s))).strip()

def add(key, **kw):
    e = books.setdefault(key, {})
    for k, v in kw.items():
        if v and (k not in e or (k == "page" and e[k] == "bookstore.html")):
            e[k] = v

# 1) Bookstore cards
src = open("bookstore.html", encoding="utf-8").read()
for c in re.findall(r'<div class="book-card">(.*?)</div>\s*</div>', src, re.S):
    t = re.search(r'class="book-title">(.*?)</div>', c, re.S)
    img = re.search(r'<img src="([^"]+)"', c)
    link = re.search(r'<a href="(https?://[^"]+)" class="payment-btn"', c)
    if not t or not link:
        continue  # PayPal-only cards (sold direct) stay on the page, not in search
    full = clean(t.group(1))
    parts = re.split(r"\s+[—–-]\s+", full, maxsplit=1)
    title, author = (parts[0], parts[1]) if len(parts) == 2 else (full, "")
    if author in SUBTITLES:  # "Title — Subtitle" cards with no author on the card
        title, author = title + ": " + author, ""
    m = re.search(r"/a/125864/(\d{13})$", link.group(1))
    key = m.group(1) if m else "direct:" + title.lower()
    add(key, title=title, author=author, isbn=m.group(1) if m else "",
        cover=img.group(1) if img else "", buy=link.group(1), page="bookstore.html")

# 2) JSON-LD on our own pages (book pages win as the "our page" link)
def ld_books(path):
    for blob in re.findall(r'<script type="application/ld\+json">(.*?)</script>', open(path, encoding="utf-8").read(), re.S):
        try:
            d = json.loads(blob)
        except ValueError:
            continue
        items = [d] if d.get("@type") == "Book" else [i.get("item", {}) for i in d.get("itemListElement", [])]
        for b in items:
            if b.get("@type") == "Book" and re.fullmatch(r"\d{13}", b.get("isbn", "")):
                yield b

for path in sorted(glob.glob("book-*.html")) + ["author-of-the-month.html", "booker-2026-shortlist.html"]:
    for b in ld_books(path):
        isbn = b["isbn"]
        page = b.get("url", "").replace("https://bookandshores.com/", "") or path
        add(isbn, title=b.get("name", ""), author=(b.get("author") or {}).get("name", ""), isbn=isbn,
            cover=b.get("image", "").replace("https://bookandshores.com/", ""), buy=AFF + isbn, page=page)
        if path.startswith("book-"):
            books[isbn]["page"] = path

for e in books.values():
    e.setdefault("author", "")
    e.setdefault("isbn", "")
    e["aff"] = e.get("buy", "").startswith(AFF)
out = sorted((e for e in books.values() if e.get("title")), key=lambda e: re.sub(r"^(the|a|an) ", "", e["title"].lower()))
with open("bookstore-search-index.js", "w", encoding="utf-8") as f:
    f.write("// B&S: bookstore search index (our picks). Generated by scripts/build_search_index.py. Do not edit by hand.\n")
    f.write("window.bsSearchIndex = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n")
print(len(out), "books")
